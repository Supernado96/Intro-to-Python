cyc1 = 10
cyc2 = 20
cyc3 = 30

avg = (cyc1 + cyc2 + cyc3) / 3

if cyc1 < avg:
    print("The first cyclist is going less than the average speed of", avg, "km/h")
if cyc2 < avg:
    print("The second cyclist is going less than the average speed of", avg, "km/h")
if cyc3 < avg:
    print("The third cyclist is going less than the average speed of", avg, "km/h")